#!/usr/bin/env python3
"""Build Orion’s Chinese fallback and its PC-matched Home numerals."""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import subprocess
import tempfile

from generate_builtin_fonts import (
    compact_ranges,
    file_sha256,
    GLYPH_COMMENT,
    npx_launcher,
    sanitize_generated_source,
)

ROOT = Path(__file__).resolve().parents[1]
ORION = ROOT / "firmware/bouffalo/boards/bl618dg/orion"
FONT_SHA256 = "84bbd4ace91d327b3ad1a581c688196278a4e41308520176f419180064e4af2b"
NOTO_SHA256 = "68543590a7c3185d69ad16664c46df28832beeb72621d2470e86b04099eb4efb"
APP_NAMES = ("clock-alarm", "netease-music", "news", "settings", "weather")
# Read source literals and JSON strings, excluding C/C++ comments.
SOURCE_TOKEN = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:[^"\\]|\\.)*"', re.DOTALL)
SOURCE_SUFFIXES = {".cpp", ".hpp", ".h", ".json"}
MISSING_UI_SYMBOLS = {0x00B7, 0x2212, 0x2605, 0x2606}
BODY_SIZE = 18
CLOCK_SIZE = 64
TEMPERATURE_SIZE = 37
FONT_DIR = ORION / "fonts"


def ui_codepoints(paths: list[Path]) -> set[int]:
    result = {0xFFFD}
    for path in paths:
        for match in SOURCE_TOKEN.finditer(path.read_text(encoding="utf-8")):
            if match[0][0] != '"':
                continue
            result.update(
                cp for cp in map(ord, match[0])
                if (cp in MISSING_UI_SYMBOLS or 0x2000 <= cp <= 0x206F or cp == 0x2103 or 0x3000 <= cp <= 0x303F
                    or 0x3400 <= cp <= 0x9FFF or 0xF900 <= cp <= 0xFAFF or 0xFF01 <= cp <= 0xFF60
                    or 0x20000 <= cp <= 0x323AF)
            )
    return result


def requested_codepoints() -> set[int]:
    paths = [
        ORION / "firmware_app.cpp",
        ORION / "orion_home.cpp",
        ROOT / "guest/sdk/calendar.hpp",
        ROOT / "guest/sdk/ui/panel.hpp",
    ]
    for app in APP_NAMES:
        paths.extend(
            path for path in (ROOT / "guest/apps" / app).rglob("*")
            if path.is_file() and path.suffix in SOURCE_SUFFIXES
        )
    return ui_codepoints(paths)


def generate(font: Path, output: Path, name: str, size: int, bpp: int, codepoints: set[int], note: str) -> None:
    ranges = ["-r", compact_ranges(codepoints - {0xFFFD})]
    if 0xFFFD in codepoints:
        ranges.extend(("-r", "0x25a1=>0xfffd"))
    with tempfile.TemporaryDirectory() as tmp:
        asset = Path(tmp) / f"{name}.c"
        subprocess.run(
            [
                npx_launcher(), "--yes", "lv_font_conv@1.5.3",
                "--font", str(font.resolve()), *ranges, "--size", str(size),
                "--bpp", str(bpp), "--format", "lvgl", "--no-compress",
                "--no-prefilter", "--lv-include", "lvgl.h", "--lv-font-name", name,
                "-o", str(asset),
            ],
            check=True,
        )
        source = sanitize_generated_source(asset.read_text(encoding="utf-8"), name, size)
    glyphs = {int(value, 16) for value in GLYPH_COMMENT.findall(source)}
    if glyphs != codepoints:
        raise ValueError(f"{name}: missing glyphs {sorted(codepoints - glyphs)}, extra {sorted(glyphs - codepoints)}")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        f"// {note}\n"
        "// Generated by tools/generate_orion_font.py.\n"
        "// clang-format off\n"
        + source,
        encoding="utf-8",
    )
    print(f"{name}: {len(glyphs)} glyphs, {size} px, {bpp} bpp")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path, help="Adobe SourceHanSansSC-Regular.otf from 2.004R")
    parser.add_argument("--numerals", type=Path, default=Path("/usr/share/fonts/truetype/noto/NotoSans-SemiBold.ttf"),
                        help="the Noto Sans SemiBold font used by PC Home")
    parser.add_argument("--output-dir", type=Path, default=FONT_DIR)
    args = parser.parse_args()
    try:
        if file_sha256(args.font) != FONT_SHA256:
            raise ValueError("expected Adobe Source Han Sans SC Regular 2.004R")
        if file_sha256(args.numerals) != NOTO_SHA256:
            raise ValueError("expected the Noto Sans SemiBold input pinned by the Guest numeral atlas")
        home = set(range(32, 127)) | {0x00B0} | ui_codepoints([
            ORION / "orion_home.cpp", ORION / "firmware_app.cpp", ROOT / "guest/apps/weather/cities.hpp",
            ROOT / "guest/apps/weather/weather_model.hpp", ROOT / "guest/sdk/ui/panel.hpp",
        ])
        source_han = "Source Han Sans SC Regular 2.004R, SIL OFL 1.1. See OFL-SourceHanSans.txt."
        settings = (
            (args.font, "font_orion_cjk", BODY_SIZE, 2, requested_codepoints(),
             "Source Han Sans SC Regular 2.004R, SIL OFL 1.1. See OFL-SourceHanSans.txt."),
            (args.numerals, "font_orion_clock", CLOCK_SIZE, 4, set(map(ord, "0123456789:-")),
             "Noto Sans SemiBold, SIL OFL 1.1. See guest/sdk/ui/NotoSans-OFL.txt."),
            (args.numerals, "font_orion_temperature", TEMPERATURE_SIZE, 4, set(map(ord, "0123456789-.°")),
             "Noto Sans SemiBold, SIL OFL 1.1. See guest/sdk/ui/NotoSans-OFL.txt."),
            (args.font, "font_orion_home", 13, 4, home, source_han),
            (args.font, "font_orion_home_value", 21, 4, set(map(ord, "0123456789月日今天")), source_han),
        )
        for font, name, size, bpp, glyphs, note in settings:
            generate(font, args.output_dir / f"{name}.c", name, size, bpp, glyphs, note)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
