"""Build the bounded offline weather city catalog from the vendored location data."""

import argparse
import json
from pathlib import Path

POPULAR = (
    "上海",
    "北京",
    "广州",
    "深圳",
    "杭州",
    "成都",
    "武汉",
    "南京",
    "重庆",
    "西安",
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    data = json.loads(args.source.read_text())
    rows = []
    provinces = []
    aliases = {
        "内蒙古自治区": "内蒙古",
        "广西壮族自治区": "广西",
        "西藏自治区": "西藏",
        "宁夏回族自治区": "宁夏",
        "新疆维吾尔自治区": "新疆",
    }
    for index, (province, cities) in enumerate(data.items()):
        short = aliases.get(
            province,
            province.removesuffix("特别行政区").removesuffix("省").removesuffix("市"),
        )
        provinces.append(short)
        assert 0 < len(cities) <= 64
        for name, coords in cities.items():
            lat, lon = coords["latitude"], coords["longitude"]
            assert 0 < lat < 55 and 70 < lon < 140, (name, coords)
            rows.append((name, index, f"latitude={lat:.4f}&longitude={lon:.4f}"))
    assert len(provinces) == 34 and len(rows) >= 300
    assert len({r[0] for r in rows}) == len(rows)
    lookup = {r[0]: r for r in rows}
    rows = [lookup[name] for name in POPULAR] + [r for r in rows if r[0] not in POPULAR]
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Location data derived from MCPKerykeion; see data/README.md and data/cities-MIT.txt.",
        "// Generated by tools/generate_weather_cities.py; edit the source catalog or generator.",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "namespace weather {",
        "struct City { const char* name; uint16_t province; const char* coordinates; };",
        "inline constexpr std::array<const char*, 34> provinces{"
        + ",".join(map(quote, provinces))
        + "};",
        f"inline constexpr std::array<City, {len(rows)}> cities{{{{",
    ]
    lines.extend(
        f"    {{{quote(name)}, {province}, {quote(coords)}}},"
        for name, province, coords in rows
    )
    lines.extend(
        [
            "}};",
            "inline constexpr unsigned PopularCityCount = 10;",
            "} // namespace weather",
            "",
        ]
    )
    args.output.write_text("\n".join(lines))
    print(
        f"Weather catalog: {len(provinces)} provinces/regions, {len(rows)} cities/locations, {len(POPULAR)} popular"
    )


if __name__ == "__main__":
    main()
