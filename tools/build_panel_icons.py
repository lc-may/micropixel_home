"""Render vendored Material Symbols Rounded SVGs into a small shared weather atlas."""

import argparse, io
from pathlib import Path
import cairosvg
from PIL import Image

NAMES = (
    "sunny",
    "partly_cloudy_day",
    "cloud",
    "foggy",
    "rainy_light",
    "rainy",
    "weather_snowy",
    "thunderstorm",
    "cloud_off",
    "alarm",
    "calendar_month",
    "event_note",
    "music_note",
    "apps",
    "add",
    "close",
    "chevron_left",
    "chevron_right",
    "refresh",
    "volume_up",
    "play_arrow",
    "pause",
    "skip_next",
    "done",
    "delete",
    "radio_button_unchecked",
    "edit",
    "timer",
    "schedule",
    "notifications_active",
    "arrow_back",
    "stop",
)
COLORS = ((245, 247, 248), (232, 161, 92), (127, 182, 217), (140, 151, 158))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    width, cell, columns = 320, 64, 5
    height = ((len(NAMES) + columns - 1) // columns) * cell
    image = Image.new("RGBA", (width, height))
    for i, name in enumerate(NAMES):
        svg = (args.source / (name + ".svg")).read_text()
        color = "#e8a15c" if i == 0 else "#8c979e" if i in (3, 8) else "#f5f7f8"
        if i in (1, 4, 5, 6, 7):
            lower = "#e8a15c" if i == 7 else "#7fb6d9"
            upper = "#e8a15c" if i == 1 else "#f5f7f8"
            lower = "#f5f7f8" if i == 1 else lower
            defs = f'<defs><linearGradient id="weather" x1="0" y1="0" x2="0" y2="1"><stop offset="45%" stop-color="{upper}"/><stop offset="64%" stop-color="{lower}"/></linearGradient></defs>'
            svg = svg.replace("<path ", defs + '<path fill="url(#weather)" ', 1)
        else:
            svg = svg.replace("<path ", f'<path fill="{color}" ', 1)
        data = cairosvg.svg2png(
            bytestring=svg.encode(), output_width=cell, output_height=cell
        )
        image.paste(
            Image.open(io.BytesIO(data)), ((i % columns) * cell, (i // columns) * cell)
        )
    indices = []
    for r, g, b, a in image.getdata():
        index = (
            min(
                range(4),
                key=lambda j: sum((COLORS[j][k] - (r, g, b)[k]) ** 2 for k in range(3)),
            )
            if a
            else 0
        )
        indices.append((index << 4) | round(a / 17))
    encoded = []
    prev = None
    n = 0
    for value in indices:
        if prev != value or n == 255:
            if n:
                encoded.extend((n, prev))
            prev = value
            n = 0
        n += 1
    encoded.extend((n, prev))
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Material Symbols Rounded by Google; see icons/README.md. Generated by tools/build_panel_icons.py.",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "#include <span>",
        "namespace micropixel::ui::material_art {",
        f"inline constexpr unsigned Width={width}, Height={height}, Cell={cell}, Columns={columns};",
        "inline constexpr std::array<uint32_t,4> Colors{0xf5f7f8,0xe8a15c,0x7fb6d9,0x8c979e};",
        f"inline constexpr std::array<uint8_t,{len(encoded)}> Coverage{{",
    ]
    lines.extend(
        "    " + ",".join(map(str, encoded[i : i + 32])) + ","
        for i in range(0, len(encoded), 32)
    )
    lines.append("};")
    lines.append(
        "enum class Symbol: unsigned { Sunny, PartlyCloudy, Cloud, Fog, Drizzle, Rain, Snow, Thunder, Unavailable, Alarm, Calendar, Notes, Music, Apps, Add, Close, Left, Right, Refresh, Volume, Play, Pause, Next, Done, Delete, Unchecked, Edit, Timer, Schedule, Ringing, Back, Stop };"
    )
    lines.append("""inline constexpr unsigned Index(int code) {
    if(code==0)return 0;if(code==1||code==2)return 1;if(code==3)return 2;
    if(code==45||code==48)return 3;if(code>=51&&code<=57)return 4;
    if((code>=61&&code<=67)||(code>=80&&code<=82))return 5;
    if((code>=71&&code<=77)||code==85||code==86)return 6;
    if(code==95||code==96||code==99)return 7;return 8;
}
inline bool Expand(std::span<uint8_t> pixels) {
    if(pixels.size()!=Width*Height*4)return false;
    size_t at=0;
    for(size_t i=0;i<Coverage.size();i+=2){
        if(at+Coverage[i]>Width*Height)return false;
        const auto value=Coverage[i+1];const auto color=Colors[value>>4];
        for(unsigned j=0;j<Coverage[i];++j,++at){pixels[at*4]=color;pixels[at*4+1]=color>>8;pixels[at*4+2]=color>>16;pixels[at*4+3]=(value&15)*17;}
    }
    return at==Width*Height;
}
} // namespace micropixel::ui::material_art
""")
    args.output.write_text("\n".join(lines))
    print("Material atlas: 32 icons, RLE bytes", len(encoded))


if __name__ == "__main__":
    main()
