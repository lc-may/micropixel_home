"""Generate the bounded, antialiased numeric atlas used by Guest panel widgets."""

import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    chars = "0123456789:.-°"
    width, height, cell_width, cell_height = 320, 512, 80, 128
    font = ImageFont.truetype(str(args.font), 128)
    image = Image.new("L", (width, height))
    draw = ImageDraw.Draw(image)
    advances = []
    for i, char in enumerate(chars):
        draw.text(
            ((i % 4) * cell_width, (i // 4) * cell_height + 110),
            char,
            font=font,
            fill=255,
            anchor="ls",
            stroke_width=0,
        )
        advances.append(round(font.getlength(char)))
    encoded = []
    previous, count = None, 0
    for value in image.tobytes():
        if value != previous or count == 255:
            if count:
                encoded.extend((count, previous))
            previous, count = value, 0
        count += 1
    encoded.extend((count, previous))
    text = [
        "// SPDX-License-Identifier: OFL-1.1",
        "// Noto Sans SemiBold glyph subset. See guest/sdk/ui/NotoSans-OFL.txt.",
        "// Generated by tools/fonts/build_panel_numerals.py; edit the generator/source font.",
        "// Source SHA-256: " + hashlib.sha256(args.font.read_bytes()).hexdigest(),
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "namespace micropixel::ui::numerals_data {",
        "inline constexpr int Width = 320, Height = 512, CellWidth = 80, CellHeight = 128;",
        "inline constexpr std::array<int, 14> Advances{"
        + ",".join(map(str, advances))
        + "};",
        f"inline constexpr std::array<uint8_t, {len(encoded)}> Coverage{{",
    ]
    text.extend(
        "    " + ",".join(map(str, encoded[i : i + 32])) + ","
        for i in range(0, len(encoded), 32)
    )
    text.extend(("};", "}  // namespace micropixel::ui::numerals_data", ""))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(text))
    print("Numeric atlas:", width, height, "RLE bytes:", len(encoded))


if __name__ == "__main__":
    main()
